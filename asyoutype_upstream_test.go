func TestTooLongNumberMatchingMultipleLeadingDigits(t *testing.T) {
	// See https://github.com/google/libphonenumber/issues/36
	// The bug occurred last time for countries which have two formatting rules with exactly the
	// same leading digits pattern but differ in length.
	f := testSet().newAsYouTypeFormatter("ZZ")
	checkInput(t, f, '+', "+")
	checkInput(t, f, '8', "+8")
	checkInput(t, f, '1', "+81 ")
	checkInput(t, f, '9', "+81 9")
	checkInput(t, f, '0', "+81 90")
	checkInput(t, f, '1', "+81 90 1")
	checkInput(t, f, '2', "+81 90 12")
	checkInput(t, f, '3', "+81 90 123")
	checkInput(t, f, '4', "+81 90 1234")
	checkInput(t, f, '5', "+81 90 1234 5")
	checkInput(t, f, '6', "+81 90 1234 56")
	checkInput(t, f, '7', "+81 90 1234 567")
	checkInput(t, f, '8', "+81 90 1234 5678")
	checkInput(t, f, '9', "+81 90 12 345 6789")
	checkInput(t, f, '0', "+81901234567890")
	checkInput(t, f, '1', "+819012345678901")
}

func TestCountryWithSpaceInNationalPrefixFormattingRule(t *testing.T) {
	f := testSet().newAsYouTypeFormatter("BY")
	checkInput(t, f, '8', "8")
	checkInput(t, f, '8', "88")
	checkInput(t, f, '1', "881")
	checkInput(t, f, '9', "8 819")
	checkInput(t, f, '0', "8 8190")
	// The formatting rule for 5 digit numbers states that no space should be present after the
	// national prefix.
	checkInput(t, f, '1', "881 901")
	checkInput(t, f, '2', "8 819 012")
	// Too long, no formatting rule applies.
	checkInput(t, f, '3', "88190123")
}

